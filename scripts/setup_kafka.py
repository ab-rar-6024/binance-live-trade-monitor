#!/usr/bin/env python3
"""
One-time Kafka setup: write a single-node KRaft config (localhost only) and format its storage.

    python scripts/setup_kafka.py

Safe to re-run: an already formatted data directory is left alone.
"""

import hashlib
import os
import shutil
import subprocess
import sys
import tarfile
import tempfile
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from backend.common.config import settings  # noqa: E402

CONFIG = settings.kafka_home / "config" / "binance-kraft.properties"

KAFKA_URL = "https://archive.apache.org/dist/kafka/3.9.1/kafka_2.13-3.9.1.tgz"
# SHA-512 of that file, checked against Apache's published checksum. A download that does not match is rejected.
KAFKA_SHA512 = ("1ea204ba73411737a275429ca976d440f007ff0957b90b19be41dc5a4bae52617267769be9f0b5791714d0b3c4c76060"
                "5bd426faea39edd90763585523fa2cfe")


def sha512_of(path: Path) -> str:
    digest = hashlib.sha512()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def safe_extract(archive: Path, dest: Path) -> None:
    """Extracts a .tgz, refusing any entry that would land outside `dest` (path traversal) or is a link."""
    dest = dest.resolve()
    with tarfile.open(archive) as tar:
        for member in tar.getmembers():
            target = (dest / member.name).resolve()
            if dest not in target.parents and target != dest:
                raise ValueError(f"refusing to extract {member.name!r}: it points outside the target folder")
            if member.issym() or member.islnk():
                raise ValueError(f"refusing to extract link {member.name!r}")
        tar.extractall(dest)


def install_kafka(url: str = KAFKA_URL, expected_sha512: str = KAFKA_SHA512) -> None:
    """Downloads Apache Kafka, verifies its checksum, and unpacks it into ./kafka."""
    with tempfile.TemporaryDirectory() as tmp:
        tmp_dir = Path(tmp)
        archive = tmp_dir / "kafka.tgz"
        print(f"Downloading {url} (about 100 MB) ...")
        urllib.request.urlretrieve(url, archive)
        actual = sha512_of(archive)
        if actual != expected_sha512:
            sys.exit(f"Checksum mismatch, refusing to use the download. Expected {expected_sha512} but got {actual}.")
        print("Checksum OK. Unpacking ...")
        unpacked = tmp_dir / "unpacked"
        safe_extract(archive, unpacked)
        (root,) = [d for d in unpacked.iterdir() if d.is_dir()]
        shutil.move(str(root), str(settings.kafka_home))
    print("Kafka installed in", settings.kafka_home)


def java_env() -> dict:
    env = dict(os.environ)
    if not env.get("JAVA_HOME"):
        default = Path(r"C:\Program Files\Eclipse Adoptium\jdk-17.0.20.101-hotspot")
        if default.exists():
            env["JAVA_HOME"] = str(default)
    env["KAFKA_HEAP_OPTS"] = env.get("KAFKA_HEAP_OPTS", "-Xmx512m -Xms512m")
    return env


def script(name: str) -> str:
    sub = "windows" if os.name == "nt" else ""
    ext = ".bat" if os.name == "nt" else ".sh"
    return str(settings.kafka_home / "bin" / sub / f"{name}{ext}")


def write_config() -> None:
    data_dir = settings.kafka_data.as_posix()
    CONFIG.write_text(
        f"""# Single-node KRaft broker for local development (generated by scripts/setup_kafka.py)
process.roles=broker,controller
node.id=1
controller.quorum.voters=1@127.0.0.1:9093
controller.listener.names=CONTROLLER
listeners=PLAINTEXT://127.0.0.1:9092,CONTROLLER://127.0.0.1:9093
advertised.listeners=PLAINTEXT://127.0.0.1:9092
inter.broker.listener.name=PLAINTEXT
listener.security.protocol.map=CONTROLLER:PLAINTEXT,PLAINTEXT:PLAINTEXT
log.dirs={data_dir}
num.partitions={settings.partitions}
offsets.topic.replication.factor=1
transaction.state.log.replication.factor=1
transaction.state.log.min.isr=1
auto.create.topics.enable=false
# Keep data for 3 days. Segments are large so Windows (which cannot delete memory-mapped
# files while open) rarely has anything to delete.
log.retention.hours=72
log.segment.bytes=134217728
log.retention.check.interval.ms=600000
""",
        encoding="utf-8",
    )


def main() -> None:
    if not settings.kafka_home.exists():
        install_kafka()
    settings.kafka_data.mkdir(parents=True, exist_ok=True)
    write_config()
    env = java_env()
    if (settings.kafka_data / "meta.properties").exists():
        print("Kafka storage already formatted:", settings.kafka_data)
        return
    cluster_id = subprocess.run([script("kafka-storage"), "random-uuid"], env=env, capture_output=True, text=True,
                                check=True).stdout.strip().splitlines()[-1]
    subprocess.run([script("kafka-storage"), "format", "-t", cluster_id, "-c", str(CONFIG)], env=env, check=True)
    print("Formatted Kafka storage with cluster id", cluster_id)


if __name__ == "__main__":
    main()
